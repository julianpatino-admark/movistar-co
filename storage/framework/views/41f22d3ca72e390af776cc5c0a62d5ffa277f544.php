<h5>3. Administración de “Cookies” en el navegador</h5>

<p>El Usuario tiene la opción de permitir, bloquear o eliminar las 'cookies' instaladas en
    su equipo mediante la configuración de las opciones del navegador instalado en su
    equipo. Al desactivar cookies, algunos de los servicios disponibles podrían dejar de
    estar operativos y podrían perder o afectar algunas funcionalidades del sitio, como,
    por ejemplo:</p>

<ul>
    <ol>1. Poder ingresar a los Portales sin necesidad de indicar en cada ocasión su
        usuario y contraseña.</ol>
    <ol>2. Acceso al contenido sin restricción dentro de los Portales.</ol>
    <ol>3. Seguridad en el uso de la información que se ingresa en los Portales.</ol>
    <ol>4. Rapidez en el uso de algún servicio dentro de los Portales.</ol>
</ul>

<p>La forma de deshabilitar las “cookies” es diferente para cada navegador, pero
    normalmente puede hacerse desde el menú Herramientas u Opciones.</p>

<p>Por ejemplo, puede encontrar información sobre cómo hacerlo en el caso de que utilice
    los siguientes navegadores:</p>

<ul>
    <li>Con Internet Explorer: Tools -> Internet Options -> Privacy (también disponible
        en el siguiente enlace: Cookies Internet Explorer).</li>
    <li>Con Firefox: Tools -> Internet Options -> Privacy (también disponible en el
        siguiente enlace: Cookies Mozilla Firefox).</li>
    <li>Con Google Chrome: Setup -> Preferences -> Security -> View (también
        disponible en el siguiente enlace: Cookies Google Chrome ).</li>
</ul>

